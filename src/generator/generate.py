"""
Synthetic settlement-reconciliation data generator.

Produces three files:
  - data/orders_ledger.csv     — merchant's internal view of what they sold
  - data/settlement_file.csv   — aggregator's view of what was paid out
  - data/ground_truth.json     — per-order correct classification (test-only)

Everything is deterministic under a seed. The scenario mix is fixed and
documented; each scenario is generated by its own small function so the
logic is easy to defend line-by-line.

Ground truth is written for tests and the final accuracy report only —
the reconciler itself must never read it (that would be cheating).
"""
from __future__ import annotations

import argparse
import csv
import json
import random
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from decimal import Decimal, ROUND_HALF_UP
from pathlib import Path
from typing import Callable, Optional

from src.models import Order, Payout
from src.tolerance import rounding_tolerance

# --------------------------------------------------------------------------
# Constants — the "physics" of the synthetic world
# --------------------------------------------------------------------------

# Cutoff for this reconciliation batch. Settlements that fall inside the
# window [RECON_DATE - WINDOW, RECON_DATE] belong to this batch.
RECON_DATE = datetime(2026, 8, 20, 18, 0, 0, tzinfo=timezone.utc)
WINDOW = timedelta(hours=24)
BATCH_ID = f"BATCH-{RECON_DATE.date().isoformat()}"

# Fee rates modeled on real Indian PA fee structures (indicative).
FEE_RATES = {
    "card": Decimal("0.02"),          # 2.00%
    "upi": Decimal("0.005"),          # 0.50%
    "netbanking": Decimal("0.015"),   # 1.50%
}
GST_MULTIPLIER = Decimal("1.18")      # 18% GST on the fee

# Scenario mix — sums to 63.
# The count of each scenario is intentional, not incidental:
#   - "clean" is the throughput signal (most work should be auto-matched)
#   - the LLM tier (fee_variance, splits, refunds, timing) is small
#     because LLM calls cost money and we want to prove logic can carry
#     most of the load
#   - genuine_mismatch has 3, including 2 near-misses, because that is
#     the hostile input the validation guard exists to defeat
SCENARIO_MIX = {
    "clean":                      45,
    "fee_variance":                5,
    "rounding":                    3,
    "split_payout_clean":          3,
    "split_payout_messy":          1,
    "partial_refund":              2,
    "timing_window":               1,
    "genuine_mismatch_orphan":     1,
    "genuine_mismatch_near_miss":  2,
}


# --------------------------------------------------------------------------
# Domain types (generator-only; Order and Payout live in src.models)
# --------------------------------------------------------------------------

@dataclass
class GroundTruth:
    key: str                      # order_id (or the fake ref for orphans)
    expected_category: str
    scenario: str
    notes: str


# --------------------------------------------------------------------------
# Small helpers
# --------------------------------------------------------------------------

def money(x) -> Decimal:
    """Snap a value to two decimal places (paisa-accurate INR)."""
    return Decimal(str(x)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def iso(dt: datetime) -> str:
    """ISO-8601 with Z suffix (aggregator files commonly use this)."""
    return dt.isoformat().replace("+00:00", "Z")


def _fee_with_gst(gross: Decimal, rate: Decimal) -> Decimal:
    return money(gross * rate * GST_MULTIPLIER)


# --------------------------------------------------------------------------
# ID / timestamp factories — closures returned by generate()
# --------------------------------------------------------------------------

def _make_id_factory(prefix: str) -> Callable[[], str]:
    counter = 0
    def _next() -> str:
        nonlocal counter
        counter += 1
        return f"{prefix}-{counter:04d}"
    return _next


def _make_time_factory(rng: random.Random) -> tuple[Callable[[], datetime], Callable[[datetime], datetime]]:
    """
    Return (pick_settled_in_window, pick_created_before).

    Order matters: we pick settled_at FIRST, uniformly inside the window
    with a 1h buffer from RECON_DATE (so a split's second leg + 30-45min
    still lands in-window). Then we pick created_at 15min-6h before that.

    Earlier, we did it the other way — picked created_at up to 49h before
    RECON, then added lag — and 40%+ of settlements ended up outside the
    window because the created_at range was wider than the window.
    """
    _WINDOW_START = RECON_DATE - WINDOW
    _MARGIN_FROM_START = timedelta(minutes=15)
    _MARGIN_FROM_END = timedelta(hours=1)      # headroom for split legs

    _span_seconds = int(((RECON_DATE - _MARGIN_FROM_END) -
                         (_WINDOW_START + _MARGIN_FROM_START)).total_seconds())

    def pick_settled_in_window() -> datetime:
        offset = rng.randint(0, _span_seconds)
        return _WINDOW_START + _MARGIN_FROM_START + timedelta(seconds=offset)

    def pick_created_before(settled_at: datetime) -> datetime:
        lag = timedelta(seconds=rng.randint(15 * 60, 6 * 3600))
        return settled_at - lag

    return pick_settled_in_window, pick_created_before


def _pick_times(times) -> tuple[datetime, datetime]:
    """(created_at, settled_at) — settled_at guaranteed in-window."""
    settled_at = times[0]()
    created_at = times[1](settled_at)
    return created_at, settled_at


# --------------------------------------------------------------------------
# Scenario builders — one per row of SCENARIO_MIX
#
# Each returns (orders_to_add, payouts_to_add, ground_truth_entry).
# Keeping them as pure functions makes each scenario reviewable in
# isolation and testable if we ever want scenario-level unit tests.
# --------------------------------------------------------------------------

def _clean_order(rng, next_order, created_at) -> Order:
    method = rng.choice(list(FEE_RATES.keys()))
    gross = money(Decimal(rng.randint(10000, 500000)) / 100)  # ₹100 – ₹5000
    fee = _fee_with_gst(gross, FEE_RATES[method])
    return Order(
        order_id=next_order(),
        gross_amount=gross,
        expected_fee=fee,
        net_expected=money(gross - fee),
        status="captured",
        created_at=created_at,
    )


def build_clean(rng, next_order, next_payout, times):
    created_at, settled_at = _pick_times(times)
    o = _clean_order(rng, next_order, created_at)
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=o.net_expected,
        fee_charged=o.expected_fee,
        settled_at=settled_at,
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(o.order_id, "MATCHED", "clean",
                     "Amount, fee, and timing all line up.")
    return [o], [p], gt


def build_fee_variance(rng, next_order, next_payout, times):
    # Merchant expected 2% flat; aggregator charged 2% + 18% GST.
    # The settlement is internally consistent (settled = gross - fee_charged),
    # but disagrees with the merchant's expected_fee. Classic FEE_VARIANCE.
    method = "card"
    gross = money(Decimal(rng.randint(10000, 500000)) / 100)
    expected_fee_flat = money(gross * FEE_RATES[method])          # ledger view
    actual_fee_gst = _fee_with_gst(gross, FEE_RATES[method])       # settlement view
    created_at, settled_at = _pick_times(times)
    o = Order(
        order_id=next_order(),
        gross_amount=gross,
        expected_fee=expected_fee_flat,
        net_expected=money(gross - expected_fee_flat),
        status="captured",
        created_at=created_at,
    )
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=money(gross - actual_fee_gst),
        fee_charged=actual_fee_gst,
        settled_at=settled_at,
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(o.order_id, "FEE_VARIANCE", "fee_variance",
                     "Merchant expected fee at flat rate; aggregator charged fee + GST.")
    return [o], [p], gt


def build_rounding(rng, next_order, next_payout, times):
    # Inject a drift that is guaranteed to fall inside the principled
    # tolerance, so the deterministic matcher should still MATCH.
    created_at, settled_at = _pick_times(times)
    o = _clean_order(rng, next_order, created_at)
    tol = rounding_tolerance(o.gross_amount)
    # Drift ∈ [-tol, +tol], excluding zero.
    max_paise = int(tol * 100)
    drift_paise = rng.randint(-max_paise, max_paise)
    if drift_paise == 0:
        drift_paise = 1
    drift = money(Decimal(drift_paise) / 100)
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=money(o.net_expected + drift),
        fee_charged=o.expected_fee,
        settled_at=settled_at,
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(o.order_id, "MATCHED", "rounding",
                     f"Sub-tolerance rounding drift of ₹{drift}; within ±₹{tol}.")
    return [o], [p], gt


def build_split_payout_clean(rng, next_order, next_payout, times):
    # One order → two payout rows summing exactly to net_expected.
    # Deterministic matcher must group by order_ref and sum.
    created_at, settled_at = _pick_times(times)
    o = _clean_order(rng, next_order, created_at)
    split1_settled = money(o.net_expected * Decimal("0.6"))
    split2_settled = money(o.net_expected - split1_settled)     # exact by construction
    split1_fee = money(o.expected_fee * Decimal("0.6"))
    split2_fee = money(o.expected_fee - split1_fee)
    p1 = Payout(next_payout(), o.order_id, split1_settled, split1_fee, settled_at, BATCH_ID)
    p2 = Payout(next_payout(), o.order_id, split2_settled, split2_fee,
                settled_at + timedelta(minutes=30), BATCH_ID)
    gt = GroundTruth(o.order_id, "SPLIT_PAYOUT", "split_payout_clean",
                     "Single order paid out across two rows; sum equals net_expected.")
    return [o], [p1, p2], gt


def build_split_payout_messy(rng, next_order, next_payout, times):
    # Two payout rows whose settled + fee amounts do NOT reconcile to
    # net_expected (gap far outside tolerance). The deterministic matcher
    # must escalate to the LLM. Ground-truth classification is a split
    # with a fee variance — the LLM should recognize both.
    created_at, settled_at = _pick_times(times)
    gross = money(Decimal("6300.00"))
    fee = _fee_with_gst(gross, FEE_RATES["card"])          # 148.68
    o = Order(
        order_id=next_order(),
        gross_amount=gross,
        expected_fee=fee,
        net_expected=money(gross - fee),
        status="captured",
        created_at=created_at,
    )
    # Deliberately off: sum(settled) = 5900, sum(fee) = 180, total = 6080
    # vs gross 6300 → unexplained gap of ₹71.32 relative to net.
    p1 = Payout(next_payout(), o.order_id, money("3500.00"), money("80.00"),
                settled_at, BATCH_ID)
    p2 = Payout(next_payout(), o.order_id, money("2400.00"), money("100.00"),
                settled_at + timedelta(minutes=45), BATCH_ID)
    gt = GroundTruth(o.order_id, "SPLIT_PAYOUT_WITH_VARIANCE", "split_payout_messy",
                     "Split across two payouts, but sums don't reconcile — LLM must classify.")
    return [o], [p1, p2], gt


def build_partial_refund(rng, next_order, next_payout, times):
    # Merchant refunded part of the order; aggregator settled net of
    # refund on the original order_ref. Ledger status marks it, so the
    # LLM's PARTIAL_REFUND claim can be corroborated by the guard.
    method = rng.choice(list(FEE_RATES.keys()))
    gross = money(Decimal(rng.randint(50000, 500000)) / 100)   # ₹500 – ₹5000
    expected_fee = _fee_with_gst(gross, FEE_RATES[method])
    refund_amount = money(gross * Decimal(rng.choice(["0.2", "0.3", "0.5"])))
    created_at, settled_at = _pick_times(times)
    o = Order(
        order_id=next_order(),
        gross_amount=gross,
        expected_fee=expected_fee,
        net_expected=money(gross - expected_fee),
        status="partially_refunded",
        created_at=created_at,
    )
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=money(gross - expected_fee - refund_amount),
        fee_charged=expected_fee,
        settled_at=settled_at,
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(o.order_id, "PARTIAL_REFUND", "partial_refund",
                     f"Order partially refunded by ₹{refund_amount}; settlement is net of refund.")
    return [o], [p], gt


def build_timing_window(rng, next_order, next_payout, times):
    # Order created in-window, but settlement lands AFTER the cutoff, so
    # this batch's file doesn't contain it. The next batch will.
    # (We use _pick_times to consume RNG in the same shape as other
    # scenarios, then discard the picked settled_at.)
    created_at, _ = _pick_times(times)
    o = _clean_order(rng, next_order, created_at)
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=o.net_expected,
        fee_charged=o.expected_fee,
        settled_at=RECON_DATE + timedelta(hours=3),                 # outside window
        batch_id=f"BATCH-{(RECON_DATE + timedelta(days=1)).date().isoformat()}",
    )
    gt = GroundTruth(o.order_id, "TIMING_WINDOW", "timing_window",
                     "Settlement cleared after this batch's cutoff.")
    return [o], [p], gt


def build_genuine_mismatch_orphan(rng, next_order, next_payout, times):
    # A payout row referencing an order that does not exist in the ledger.
    # No order is added. Fake ref uses the ORD-9xxx band so it won't
    # collide with the ORD-0001..ORD-0063 sequence.
    fake_ref = f"ORD-9{rng.randint(100, 999)}"
    gross = money(Decimal(rng.randint(10000, 200000)) / 100)
    fee = _fee_with_gst(gross, FEE_RATES["card"])
    p = Payout(
        payout_id=next_payout(),
        order_ref=fake_ref,
        settled_amount=money(gross - fee),
        fee_charged=fee,
        settled_at=RECON_DATE - timedelta(hours=rng.randint(1, 20)),
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(fake_ref, "GENUINE_MISMATCH", "genuine_mismatch_orphan",
                     "Payout references an order_id not present in the merchant ledger.")
    return [], [p], gt


# Adversarial near-misses — hardcoded numbers so tests can assert on them.
# Each is an order+payout pair where:
#   • order.status == 'captured' (no refund event to appeal to)
#   • settled_amount != gross - fee_charged (settlement internally inconsistent)
#   • gap is far outside the rounding tolerance
# The LLM will be tempted to fabricate a fee-adjustment or partial-refund
# explanation; the validation guard must reject any such claim because
# the numbers don't actually close.
_NEAR_MISSES = [
    {
        "gross":  Decimal("4823.00"),
        "expected_fee": Decimal("96.46"),      # 2.00% flat
        "settled_amount": Decimal("4703.20"),  # gap ₹23.34 vs expected net
        "fee_charged": Decimal("96.46"),       # fee unchanged, so gap is unexplained
        "temptation": "LLM may claim FEE_VARIANCE ~₹23; fails guard because fee_charged is unchanged.",
    },
    {
        "gross":  Decimal("8945.00"),
        "expected_fee": Decimal("211.10"),     # 2.00% + 18% GST
        "settled_amount": Decimal("8600.00"),  # gap ₹133.90 vs expected net
        "fee_charged": Decimal("211.10"),
        "temptation": "LLM may claim PARTIAL_REFUND ~₹134; fails guard because ledger status is 'captured'.",
    },
]
_near_miss_iter = iter(_NEAR_MISSES)


def build_genuine_mismatch_near_miss(rng, next_order, next_payout, times):
    spec = next(_near_miss_iter)
    created_at, settled_at = _pick_times(times)
    o = Order(
        order_id=next_order(),
        gross_amount=spec["gross"],
        expected_fee=spec["expected_fee"],
        net_expected=money(spec["gross"] - spec["expected_fee"]),
        status="captured",                       # deliberately NOT refunded
        created_at=created_at,
    )
    p = Payout(
        payout_id=next_payout(),
        order_ref=o.order_id,
        settled_amount=spec["settled_amount"],
        fee_charged=spec["fee_charged"],
        settled_at=settled_at,
        batch_id=BATCH_ID,
    )
    gt = GroundTruth(o.order_id, "GENUINE_MISMATCH", "genuine_mismatch_near_miss",
                     "Near-miss adversarial: " + spec["temptation"])
    return [o], [p], gt


SCENARIO_BUILDERS: dict[str, Callable] = {
    "clean":                     build_clean,
    "fee_variance":              build_fee_variance,
    "rounding":                  build_rounding,
    "split_payout_clean":        build_split_payout_clean,
    "split_payout_messy":        build_split_payout_messy,
    "partial_refund":            build_partial_refund,
    "timing_window":             build_timing_window,
    "genuine_mismatch_orphan":   build_genuine_mismatch_orphan,
    "genuine_mismatch_near_miss": build_genuine_mismatch_near_miss,
}


# --------------------------------------------------------------------------
# Top-level orchestration
# --------------------------------------------------------------------------

def generate(seed: int, out_dir: Path) -> dict:
    rng = random.Random(seed)
    # Reset near-miss iterator so repeat runs behave the same.
    global _near_miss_iter
    _near_miss_iter = iter(_NEAR_MISSES)

    out_dir.mkdir(parents=True, exist_ok=True)
    orders: list[Order] = []
    payouts: list[Payout] = []
    truths: list[GroundTruth] = []

    next_order = _make_id_factory("ORD")
    next_payout = _make_id_factory("PYT")
    times = _make_time_factory(rng)

    # Flatten the mix into a per-record sequence, then shuffle so
    # scenarios interleave naturally in the file (as a real settlement
    # file would — no block of 45 clean rows followed by a block of exceptions).
    sequence: list[str] = []
    for scenario, count in SCENARIO_MIX.items():
        sequence.extend([scenario] * count)
    rng.shuffle(sequence)

    for scenario in sequence:
        builder = SCENARIO_BUILDERS[scenario]
        new_orders, new_payouts, gt = builder(rng, next_order, next_payout, times)
        orders.extend(new_orders)
        payouts.extend(new_payouts)
        truths.append(gt)

    # Shuffle payout rows so split-payout pairs aren't visually adjacent —
    # matches how real settlement files land (batched by settle time).
    rng.shuffle(payouts)

    _write_orders(out_dir / "orders_ledger.csv", orders)
    _write_payouts(out_dir / "settlement_file.csv", payouts)
    _write_ground_truth(out_dir / "ground_truth.json", truths)

    return {
        "orders": len(orders),
        "payouts": len(payouts),
        "ground_truth_entries": len(truths),
        "scenario_mix": SCENARIO_MIX,
        "recon_date": iso(RECON_DATE),
    }


def _write_orders(path: Path, orders: list[Order]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["order_id", "gross_amount", "expected_fee",
                    "net_expected", "status", "created_at"])
        for o in orders:
            w.writerow([o.order_id, str(o.gross_amount), str(o.expected_fee),
                        str(o.net_expected), o.status, iso(o.created_at)])


def _write_payouts(path: Path, payouts: list[Payout]) -> None:
    with path.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["payout_id", "order_ref", "settled_amount",
                    "fee_charged", "settled_at", "batch_id"])
        for p in payouts:
            w.writerow([p.payout_id, p.order_ref or "",
                        str(p.settled_amount), str(p.fee_charged),
                        iso(p.settled_at), p.batch_id])


def _write_ground_truth(path: Path, truths: list[GroundTruth]) -> None:
    payload = {
        "recon_date": iso(RECON_DATE),
        "window_hours": int(WINDOW.total_seconds() // 3600),
        "batch_id": BATCH_ID,
        "scenario_mix": SCENARIO_MIX,
        "labels": [
            {
                "key": t.key,
                "expected_category": t.expected_category,
                "scenario": t.scenario,
                "notes": t.notes,
            }
            for t in truths
        ],
    }
    path.write_text(json.dumps(payload, indent=2), encoding="utf-8")


# --------------------------------------------------------------------------
# CLI
# --------------------------------------------------------------------------

def main() -> None:
    parser = argparse.ArgumentParser(description="Generate reconciliation test data.")
    parser.add_argument("--seed", type=int, default=42,
                        help="RNG seed (default: 42; keep for reproducibility)")
    parser.add_argument("--out", type=Path, default=Path("data"),
                        help="Output directory (default: ./data)")
    args = parser.parse_args()

    summary = generate(seed=args.seed, out_dir=args.out)
    print("Generated synthetic reconciliation batch")
    print(f"  recon_date : {summary['recon_date']}")
    print(f"  orders     : {summary['orders']} -> {args.out}/orders_ledger.csv")
    print(f"  payouts    : {summary['payouts']} -> {args.out}/settlement_file.csv")
    print(f"  labels     : {summary['ground_truth_entries']} -> {args.out}/ground_truth.json")
    print("  scenario mix:")
    for scenario, count in summary["scenario_mix"].items():
        print(f"    {scenario:32s} {count}")


if __name__ == "__main__":
    main()
